    val code: String,
    val displayNameId: String,
    val nativeName: String,
    val flagEmoji: String,
) {
    // Strictly ordered alphabetically: China, Indonesia, Inggris, Jepang, Jerman, Korea, Russia
    CHINA(code = "zh", displayNameId = "China", nativeName = "中文 (简体)", flagEmoji = "🇨🇳"),
    INDONESIA(code = "id", displayNameId = "Indonesia", nativeName = "Bahasa Indonesia", flagEmoji = "🇮🇩"),
    INGGRIS(code = "en", displayNameId = "Inggris", nativeName = "English", flagEmoji = "🇬🇧"),
    JEPANG(code = "ja", displayNameId = "Jepang", nativeName = "日本語", flagEmoji = "🇯🇵"),
    JERMAN(code = "de", displayNameId = "Jerman", nativeName = "Deutsch", flagEmoji = "🇩🇪"),
    KOREA(code = "ko", displayNameId = "Korea", nativeName = "한국어", flagEmoji = "🇰🇷"),
    RUSSIA(code = "ru", displayNameId = "Russia", nativeName = "Русский", flagEmoji = "🇷🇺");

    companion object {
        val alphabeticalList: List<AppLanguage> = entries.sortedBy { it.displayNameId }

        fun fromCode(code: String?): AppLanguage =
            entries.firstOrNull { it.code.equals(code?.trim(), ignoreCase = true) } ?: INDONESIA
    }
}

